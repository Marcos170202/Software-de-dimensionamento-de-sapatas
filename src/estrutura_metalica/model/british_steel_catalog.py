def _make_profile(name: str, r: dict[str, float]) -> IProfileSection:
    bf = r["B"] * 1e-3
    tf = r["T"] * 1e-3
    tw = r["t"] * 1e-3
    h = r["d"] * 1e-3
    rt = compressed_flange_radius_of_gyration(bf=bf, tf=tf, tw=tw, h=h)
    return IProfileSection(
        name=name,
        shape=SectionShape.I_H,
        area=r["area"] * 1e-4,
        ix=r["ix"] * 1e-8,
        iy=r["iy"] * 1e-8,
        j=r["j"] * 1e-8,
        depth=r["D"] * 1e-3,
        cw=r["h"] * 1e-6,
        bf=bf,
        tw=tw,
        tf=tf,
        h=h,
        wx=r["wx"] * 1e-6,
        zx=r["zx"] * 1e-6,
        wy=r["wy"] * 1e-6,
        zy=r["zy"] * 1e-6,
        rt=rt,
        mass_linear=r["mass"],
        source=_SOURCE,
    )


