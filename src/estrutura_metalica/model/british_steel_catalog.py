"""Catálogo de perfis "Universal Beams" (UB) e "Universal Columns"
(UC) — British Steel.

Fonte: British Steel, "Sections — Advance UK Sections" (datasheets
técnicos, dimensões e propriedades conforme BS EN 10365:2017).
Seções laminadas de abas paralelas, dupla simetria — mesma família
geométrica dos perfis "W"/"H" Gerdau (ver
:mod:`~estrutura_metalica.model.steel_profile_catalog`), por isso
reutiliza diretamente
:class:`~estrutura_metalica.model.section.IProfileSection` — ao
contrário do catálogo Gerdau I/U (abas inclinadas, ver
:mod:`~estrutura_metalica.model.legacy_profile_catalog`), este
catálogo tabula TODAS as propriedades exigidas por
``IProfileSection`` (``Wx``/``Zx``/``Wy``/``Zy``/``J``/``Cw``) —
exceto ``rt`` (raio de giração da mesa comprimida + 1/3 da alma
comprimida), não publicada por este catálogo, calculada aqui via
:func:`~estrutura_metalica.model.section.compressed_flange_radius_of_gyration`
(idealização geométrica, conferida contra o valor de catálogo do
perfil Gerdau W310x97,0 — ≈0,8% de diferença, ver docstring dessa
função).

Aço: seções British Steel são fornecidas em S275 ou S355 (BS EN
10025-2) — ``fy``/``fu`` NÃO são fixados aqui, mesma convenção de
:mod:`~estrutura_metalica.model.material` (o chamador monta um
:class:`~estrutura_metalica.model.material.SteelMaterial` à parte).

Valores extraídos do texto do PDF (``pdftotext -layout``) e
convertidos para SI (m, m², m⁴, m⁶). Conferidos por checagem
cruzada ``Ix ≈ Área·rx²`` — sem nenhuma divergência acima de 5%
nas 94 bitolas UB e 53 bitolas UC (ao contrário dos catálogos
Gerdau, este catálogo não apresentou nenhuma inconsistência
detectável).

**ATENÇÃO**: ``h`` (altura livre da alma, "depth between fillets")
é publicado diretamente pelo catálogo (coluna "d") — ao contrário
do catálogo Gerdau W/H, onde precisou ser inferido ("d'"). O
parâmetro de flambagem lateral ``u`` e o índice de esbeltez
equivalente ``x`` (Eurocode, EN 1993-1-1) publicados pelo catálogo
NÃO são reproduzidos aqui — são parâmetros específicos do método
de verificação europeu, sem equivalência direta nas fórmulas da
NBR 8800 implementadas neste pacote.
"""

