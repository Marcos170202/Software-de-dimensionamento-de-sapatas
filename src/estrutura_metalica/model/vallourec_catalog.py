def _make_circular(row: tuple[float, ...]) -> CircularHollowProfile:
    d_mm, t_mm, mass, area, i, wel, wpl, it, ct, as_surf = row
    d = d_mm * 1e-3
    t = t_mm * 1e-3
    return CircularHollowProfile(
        name=f"TC{d_mm:g}x{t_mm:g}",
        shape=SectionShape.TUBE_CIRCULAR,
        area=area * 1e-4,
        ix=i * 1e-8,
        iy=i * 1e-8,
        j=it * 1e-8,
        depth=d,
        cw=None,
        d=d,
        t=t,
        wel=wel * 1e-6,
        wpl=wpl * 1e-6,
        ct=ct * 1e-6,
        surface_area_per_length=as_surf,
        mass_linear=mass,
        source=_SOURCE,
    )


