def get_vallourec_circular_hollow_profile(name: str) -> CircularHollowProfile:
    """Busca um perfil tubular circular MSH pelo nome (ex.: ``"TC114.3x4.5"``)."""
    try:
        return VALLOUREC_CIRCULAR_HOLLOW_PROFILES[name]
    except KeyError:
        prefix = name.split("x")[0]
        similar = sorted(
            n for n in VALLOUREC_CIRCULAR_HOLLOW_PROFILES if n.startswith(prefix)
        )
        raise KeyError(
            f"Perfil {name!r} nao encontrado no catalogo Vallourec MSH circular. "
            f"Bitolas com mesmo diametro: {similar!r}"
        ) from None


