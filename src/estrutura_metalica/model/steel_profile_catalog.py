GERDAU_W_H_PROFILES: dict[str, IProfileSection] = {
    profile.name: profile for profile in _RAW_PROFILES
}


def get_gerdau_w_h_profile(name: str) -> IProfileSection:
    """Busca um perfil no catálogo Gerdau W/H pelo nome (ex.:
    ``"W310x97.0"``, ``"HP310x110.0"``).

    Levanta ``KeyError`` com uma listagem de nomes semelhantes
    quando o nome não é encontrado (evita erros silenciosos por
    formatação — ex.: usar vírgula em vez de ponto decimal, ou
    omitir a massa linear).
    """
    try:
        return GERDAU_W_H_PROFILES[name]
    except KeyError:
        prefix = name.split("x")[0]
        similar = sorted(n for n in GERDAU_W_H_PROFILES if n.startswith(prefix))
        raise KeyError(
            f"Perfil {name!r} nao encontrado no catalogo Gerdau W/H. "
            f"Bitolas da mesma serie disponiveis: {similar!r}"
        ) from None

